import { safeErrorClass } from "../application/background-tasks.ts";

type FailureSource = "uncaught_exception" | "unhandled_rejection";
type FailureLog = { level: "warn" | "error"; event: string; [key: string]: string | number };
type Options = {
  prefix: "api" | "notification_worker";
  deadlineMs: number;
  shutdown(source: FailureSource): unknown;
  log(entry: FailureLog): void;
};

/** A process fault is terminal, not permission to resume an inconsistent app.
 * Suppress Node's unredacted exception dump, request the role's normal bounded
 * cleanup, then always exit 1. The independent last-resort timer also covers a
 * broken shutdown callback. Embedded createApiServer users opt into neither
 * global handlers nor process exit; only the standalone role installs this. */
export function guardProcessFailures({ prefix, deadlineMs, shutdown, log }: Options) {
  if (!Number.isSafeInteger(deadlineMs) || deadlineMs < 100 || deadlineMs > 60_000) {
    throw new RangeError("The process failure deadline must be between 100 and 60000 milliseconds.");
  }
  if (prefix !== "api" && prefix !== "notification_worker") throw new TypeError("Unknown process failure role.");
  let state: "running" | "failing" | "disposed" = "running";
  let timer: ReturnType<typeof setTimeout> | undefined;
  let startedAt = 0;
  let secondaryFailures = 0;

  function errorName(value: unknown): string {
    // Even a hostile Error subclass may have a throwing `name` getter.
    try { return safeErrorClass(value); } catch { return "Error"; }
  }
  function emit(event: string, fields: Omit<FailureLog, "level" | "event"> = {}, level: FailureLog["level"] = "error"): void {
    try { log({ level, event: `${prefix}_${event}`, ...fields }); } catch { /* logging cannot restore successful execution */ }
  }
  function dispose(): void {
    process.off("uncaughtException", onException);
    process.off("unhandledRejection", onRejection);
    if (timer) { clearTimeout(timer); timer = undefined; }
    state = "disposed";
  }
  function exit(): never {
    dispose();
    process.exit(1);
  }
  function elapsed(): number { return Math.max(0, Math.round(performance.now() - startedAt)); }

  function fail(source: FailureSource, value: unknown): void {
    if (state === "disposed") return;
    process.exitCode = 1;
    if (state === "failing") {
      secondaryFailures = Math.min(Number.MAX_SAFE_INTEGER, secondaryFailures + 1);
      // Do not reset the deadline, replay cleanup, or log a new payload for each
      // rejected promise generated by a failing driver during teardown.
      if (secondaryFailures === 1) emit("process_failure_repeated", { source }, "warn");
      return;
    }
    state = "failing";
    startedAt = performance.now();
    // Arm before calling any observer: a broken callback must not leave a
    // process that still holds a listener but has no trustworthy application.
    timer = setTimeout(() => {
      emit("process_failure_deadline_reached", { durationMs: elapsed(), secondaryFailures });
      exit();
    }, deadlineMs);
    emit("process_failure", { source, errorName: errorName(value), deadlineMs });
    void Promise.resolve().then(() => shutdown(source)).then(() => {
      emit("process_failure_shutdown_finished", { durationMs: elapsed(), secondaryFailures, exitCode: 1 });
      exit();
    }, cause => {
      emit("process_failure_cleanup_failed", { errorName: errorName(cause), durationMs: elapsed(), secondaryFailures });
      exit();
    });
  }
  function onException(error: unknown): void { fail("uncaught_exception", error); }
  function onRejection(reason: unknown): void { fail("unhandled_rejection", reason); }
  process.on("uncaughtException", onException);
  process.on("unhandledRejection", onRejection);
  return Object.freeze({ dispose });
}
