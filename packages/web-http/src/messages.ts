import type { ApiProxyConfig } from "./api.ts";
import { errorResponse } from "./http.ts";
import { forwardAuthoringRequest } from "./forward.ts";

/**
 * 私信读侧 — the browser-facing proxy for a reader's conversations (#198).
 *
 * The conversations API has been served in full for a while: an inbox, a
 * per-conversation read, a message list with a cursor, a read marker, and a
 * compose path that requires an `Idempotency-Key`. No Web surface called any of
 * it, so "私信" existed only for clients that already knew the endpoints.
 *
 * This file covers the **read** half only — inbox, one conversation, and its
 * messages. Composing is deliberately not here: sending needs the idempotency
 * key handled end to end, and mixing "can I see my messages" with "can I write
 * one, and what happens to a retry" into a single change makes both harder to
 * review and the second one easy to get subtly wrong.
 *
 * All three routes require a session, and the API decides who may read what.
 * This proxy does not repeat that decision — but it must not launder the answer
 * either, because "not yours" and "does not exist" are security-relevant
 * distinctions the API already makes for itself.
 *
 * Nothing in this file imports a framework.
 */

/**
 * Conversation ids are UUIDs in every store this application ships.
 *
 * Unlike the follow target, which is whatever the author page happens to carry,
 * a conversation id is generated by the API itself and never typed by a user. So
 * the shape can be asserted here without the risk the follow proxy would have
 * taken: refusing anything that is not a UUID cannot lock a reader out of a real
 * conversation, because no real conversation has any other shape.
 *
 * Refusing locally also keeps a malformed id out of the API's `decodeUserId`,
 * which is intentionally permissive and would turn `..%2Fadmin` into a lookup.
 */
export const CONVERSATION_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** The inbox page size the API defaults to, and its ceiling. */
export const INBOX_DEFAULT_LIMIT = 50;
export const MESSAGES_DEFAULT_LIMIT = 100;
export const CONVERSATIONS_MAX_LIMIT = 100;

/**
 * Parse a limit, or return `null` when it is not a clean integer.
 *
 * Duplicated from the feed proxy's parser on purpose rather than shared: the two
 * have different bounds and different meaning, and a shared helper would have to
 * take both as arguments to stay honest — at which point it is the same three
 * lines with an extra call site.
 */
export function parseLimit(raw: string | null, fallback: number, max: number): number | null {
  if (raw === null || raw === "") return fallback;
  if (!/^\d+$/.test(raw)) return null;
  const value = Number(raw);
  if (!Number.isSafeInteger(value) || value < 1 || value > max) return null;
  return value;
}

export function inboxPath(limit: number): string {
  return "api/v1/conversations?limit=" + limit;
}

export function conversationPath(conversationId: string): string {
  return "api/v1/conversations/" + encodeURIComponent(conversationId);
}

/**
 * The message page path.
 *
 * `before` is an opaque cursor as far as the browser is concerned: the API
 * decodes it into a message id and reads everything older than that row. This
 * proxy forwards it unchanged when present and omits it otherwise, which is what
 * "no cursor" means — an explicit `before=` is not the same request.
 */
export function messagesPath(conversationId: string, limit: number, before: string | null): string {
  const base = "api/v1/conversations/" + encodeURIComponent(conversationId) + "/messages?limit=" + limit;
  return before === null ? base : base + "&before=" + encodeURIComponent(before);
}

function isConversationId(value: string): boolean {
  return CONVERSATION_ID_PATTERN.test(value);
}

/** The read-only method check shared by the three routes. */
function requireGet(request: Request): Response | null {
  if (request.method === "GET") return null;
  return errorResponse("METHOD_NOT_ALLOWED", "Only GET is supported for reading messages.", 405);
}

/**
 * `GET /api/inbox` — the conversations this reader is part of.
 *
 * An inbox is private, so a signed-out caller gets the API's `401` rather than
 * an empty list: "you have no conversations" and "you are not signed in" are
 * different statements and the reader acts differently on each.
 */
export async function handleInboxRequest(
  request: Request,
  params: { limit?: string | null },
  config: ApiProxyConfig = {},
): Promise<Response> {
  const wrongMethod = requireGet(request);
  if (wrongMethod) return wrongMethod;

  const limit = parseLimit(params.limit ?? null, INBOX_DEFAULT_LIMIT, CONVERSATIONS_MAX_LIMIT);
  if (limit === null) {
    return errorResponse("BAD_USER_INPUT", "Invalid limit query parameter.", 400);
  }
  return forwardAuthoringRequest(request, inboxPath(limit), "GET", config);
}

/**
 * `GET /api/inbox/:id` — one conversation's header: participants, unread count,
 * last message.
 *
 * The API answers `404` both for "no such conversation" and for "not a member",
 * and that is the right answer: membership should not be discoverable by
 * guessing ids. This proxy forwards it unchanged; a `403` invented here would be
 * a different, less careful answer than the one the API chose.
 */
export async function handleConversationRequest(
  request: Request,
  params: { conversationId: string },
  config: ApiProxyConfig = {},
): Promise<Response> {
  const wrongMethod = requireGet(request);
  if (wrongMethod) return wrongMethod;

  if (!isConversationId(params.conversationId)) {
    return errorResponse("BAD_USER_INPUT", "Invalid conversation ID.", 400);
  }
  return forwardAuthoringRequest(request, conversationPath(params.conversationId), "GET", config);
}

/**
 * `GET /api/inbox/:id/messages` — one page of a conversation, oldest first.
 *
 * Note the asymmetry with `handleConversationRequest`, which is the API's and not
 * this proxy's: a message list for a conversation the caller is not part of
 * answers `403 FORBIDDEN`, while the conversation itself answers `404`. Both are
 * read-only and neither leaks message content, but the 403 does confirm that a
 * conversation with that id exists. Forwarded unchanged rather than normalised
 * here — rewriting it would hide the distinction from anyone who could fix it,
 * and this proxy is not the place that decides what a membership failure means.
 */
export async function handleConversationMessagesRequest(
  request: Request,
  params: { conversationId: string; limit?: string | null; before?: string | null },
  config: ApiProxyConfig = {},
): Promise<Response> {
  const wrongMethod = requireGet(request);
  if (wrongMethod) return wrongMethod;

  if (!isConversationId(params.conversationId)) {
    return errorResponse("BAD_USER_INPUT", "Invalid conversation ID.", 400);
  }
  const limit = parseLimit(params.limit ?? null, MESSAGES_DEFAULT_LIMIT, CONVERSATIONS_MAX_LIMIT);
  if (limit === null) {
    return errorResponse("BAD_USER_INPUT", "Invalid limit query parameter.", 400);
  }

  // The cursor is opaque here, but an empty one is not a cursor: forwarding
  // `before=` would ask the API to decode an empty string and answer 400, which
  // looks like a client bug rather than the absent cursor it actually is.
  const before = params.before ?? null;
  if (before !== null && before.trim() === "") {
    return errorResponse("BAD_USER_INPUT", "The message cursor must not be empty.", 400);
  }

  return forwardAuthoringRequest(
    request,
    messagesPath(params.conversationId, limit, before),
    "GET",
    config,
  );
}
