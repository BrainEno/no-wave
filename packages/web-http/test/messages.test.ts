import assert from "node:assert/strict";
import test from "node:test";

import {
  CONVERSATION_ID_PATTERN,
  INBOX_DEFAULT_LIMIT,
  MESSAGES_DEFAULT_LIMIT,
  conversationPath,
  handleConversationMessagesRequest,
  handleConversationRequest,
  handleInboxRequest,
  inboxPath,
  messagesPath,
  parseLimit,
} from "../src/messages.ts";
import { ACCESS_TOKEN_COOKIE } from "../src/policy.ts";
import { API_BASE, TOKENS, assertNoStore, json, stubFetch } from "./helpers.ts";

/**
 * Private-message read proxy contract (#198).
 *
 * The conversations API has been complete for a while and no Web surface called
 * it. These tests cover the read half — inbox, one conversation, its messages —
 * and the distinctions that make it safe to expose:
 *
 *   - signed out is `401`, never an empty inbox (those mean different things)
 *   - a conversation you are not part of is `404`, indistinguishable from absent
 *   - a message list is `403` for the same situation, which is the API's own
 *     asymmetry and is forwarded rather than "tidied up" here
 */

const CONVERSATION = "c81407b1-4680-469d-9de4-2c34f042081c";
const CURSOR = "9b63db5c-5fe2-4639-9037-b8c6d88ec767";

function upstream(body: unknown = { data: [] }, status = 200) {
  const stub = stubFetch({
    "api/v1/conversations": () => json(body, status),
  });
  return { calls: stub.calls, stub, config: { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl } };
}

function get(path: string, options: { cookie?: string; method?: string } = {}): Request {
  const headers: Record<string, string> = { host: "no-wave.test", accept: "application/json" };
  if (options.cookie) headers.cookie = options.cookie;
  return new Request(`https://no-wave.test${path}`, { method: options.method ?? "GET", headers });
}

const SIGNED_IN = `${ACCESS_TOKEN_COOKIE}=${TOKENS.accessToken}`;

test("the inbox carries the session as a bearer token", async () => {
  const { config, calls } = upstream({ data: [{ id: CONVERSATION, unreadCount: 2 }] });
  const response = await handleInboxRequest(get("/api/inbox", { cookie: SIGNED_IN }), { limit: null }, config);
  assert.equal(response.status, 200);
  assertNoStore(response);
  assert.equal(calls[0].init?.method, "GET");
  assert.equal(new Headers(calls[0].init?.headers).get("authorization"), `Bearer ${TOKENS.accessToken}`);
  assert.equal(new Headers(calls[0].init?.headers).get("cookie"), null);
  assert.ok(calls[0].url.includes("api/v1/conversations?limit=50"), calls[0].url);
});

test("signed out is a 401, not an empty inbox", async () => {
  // "You have no conversations" and "you are not signed in" are different
  // statements, and a reader acts differently on each. An empty list here would
  // tell a signed-out reader their inbox is empty.
  const stub = stubFetch({
    "api/v1/conversations": () => json({ error: { code: "UNAUTHENTICATED", message: "Authentication is required." } }, 401),
  });
  const response = await handleInboxRequest(get("/api/inbox"), { limit: null }, {
    apiBaseUrl: API_BASE,
    fetchImpl: stub.fetchImpl,
  });
  assert.equal(response.status, 401);
  assert.equal(stub.calls.length, 1, "the API decides, and the answer is passed through");
  assert.equal(new Headers(stub.calls[0].init?.headers).get("authorization"), null);
});

test("an empty inbox is forwarded as an empty list", async () => {
  const { config } = upstream({ data: [] });
  const response = await handleInboxRequest(get("/api/inbox"), { limit: null }, config);
  assert.equal(response.status, 200);
  const body = await response.json() as { data?: unknown[] };
  assert.deepEqual(body.data, []);
});

test("the inbox limit is defaulted and bounded", async () => {
  const { config, calls } = upstream();
  await handleInboxRequest(get("/api/inbox"), { limit: null }, config);
  assert.ok(calls[0].url.includes(`limit=${INBOX_DEFAULT_LIMIT}`), calls[0].url);

  for (const bad of ["0", "101", "1.5", "1e3", "abc", "-1"]) {
    const response = await handleInboxRequest(get("/api/inbox"), { limit: bad }, config);
    assert.equal(response.status, 400, JSON.stringify(bad));
  }
  assert.equal(calls.length, 1, "a bad limit never reaches the API");
});

test("a conversation id must be a UUID before it is forwarded", async () => {
  // Generated by the API, never typed by a user, so the shape is safe to assert.
  // It also keeps a malformed id out of the API's permissive `decodeUserId`.
  const { config, calls } = upstream();
  for (const bad of ["", "abc", "a/b", "..", `${CONVERSATION}x`, CONVERSATION.slice(0, -1)]) {
    const response = await handleConversationRequest(get(`/api/inbox/${bad}`), { conversationId: bad }, config);
    assert.equal(response.status, 400, JSON.stringify(bad));
  }
  assert.equal(calls.length, 0);
});

test("a conversation the reader is not part of is passed through as 404", async () => {
  // The API answers 404 both for "no such conversation" and "not a member": with
  // ids that can be guessed, membership must not be discoverable. Inventing a
  // 403 here would be a different and less careful answer than the API's.
  const stub = stubFetch({
    "api/v1/conversations": () => json({ error: { code: "NOT_FOUND", message: "The conversation was not found." } }, 404),
  });
  const response = await handleConversationRequest(
    get(`/api/inbox/${CONVERSATION}`, { cookie: SIGNED_IN }),
    { conversationId: CONVERSATION },
    { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
  );
  assert.equal(response.status, 404);
  assert.equal(stub.calls.length, 1);
});

test("the message list forwards the API's 403 rather than tidying it into 404", async () => {
  // Deliberately not normalised. The API confirms existence here and hides it on
  // the conversation route; that inconsistency is real, belongs to the API, and
  // a proxy that rewrote it would hide it from the people who can fix it.
  const stub = stubFetch({
    "api/v1/conversations": () => json({ error: { code: "FORBIDDEN", message: "You are not allowed to access this resource." } }, 403),
  });
  const response = await handleConversationMessagesRequest(
    get(`/api/inbox/${CONVERSATION}/messages`, { cookie: SIGNED_IN }),
    { conversationId: CONVERSATION, limit: null, before: null },
    { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
  );
  assert.equal(response.status, 403);
  const body = await response.json() as { error?: { code?: string } };
  assert.equal(body.error?.code, "FORBIDDEN", "the status and the code reach the client unchanged");
});

test("the cursor is forwarded when present and omitted when absent", async () => {
  const { config, calls } = upstream();
  await handleConversationMessagesRequest(
    get(`/api/inbox/${CONVERSATION}/messages?before=${CURSOR}`),
    { conversationId: CONVERSATION, limit: null, before: CURSOR },
    config,
  );
  assert.ok(calls[0].url.includes(`before=${CURSOR}`), calls[0].url);

  await handleConversationMessagesRequest(
    get(`/api/inbox/${CONVERSATION}/messages`),
    { conversationId: CONVERSATION, limit: null, before: null },
    config,
  );
  assert.ok(!calls[1].url.includes("before="), `an absent cursor must not be sent: ${calls[1].url}`);
  assert.ok(calls[1].url.includes(`limit=${MESSAGES_DEFAULT_LIMIT}`), calls[1].url);
});

test("an empty cursor is refused instead of asked of the API", async () => {
  // `before=` would reach the API as an empty string to decode and come back as
  // a 400 that looks like a client bug, when what actually happened is that
  // there was no cursor.
  const { config, calls } = upstream();
  const response = await handleConversationMessagesRequest(
    get(`/api/inbox/${CONVERSATION}/messages?before=`),
    { conversationId: CONVERSATION, limit: null, before: "" },
    config,
  );
  assert.equal(response.status, 400);
  assert.equal(calls.length, 0);
});

test("read routes refuse every write verb", async () => {
  const { config, calls } = upstream();
  for (const method of ["POST", "PUT", "PATCH", "DELETE"]) {
    assert.equal((await handleInboxRequest(get("/api/inbox", { method }), { limit: null }, config)).status, 405, method);
    assert.equal(
      (await handleConversationRequest(get(`/api/inbox/${CONVERSATION}`, { method }), { conversationId: CONVERSATION }, config)).status,
      405,
      method,
    );
    assert.equal(
      (await handleConversationMessagesRequest(
        get(`/api/inbox/${CONVERSATION}/messages`, { method }),
        { conversationId: CONVERSATION, limit: null, before: null },
        config,
      )).status,
      405,
      method,
    );
  }
  assert.equal(calls.length, 0, "a write verb never reaches a read endpoint");
});

test("an unconfigured API is a 503, not an empty inbox", async () => {
  const response = await handleInboxRequest(get("/api/inbox"), { limit: null }, {});
  assert.equal(response.status, 503);
});

test("an upstream failure is passed through, with no caching", async () => {
  const stub = stubFetch({
    "api/v1/conversations": () => json({ error: { code: "SERVICE_UNAVAILABLE", message: "try later" } }, 500),
  });
  const response = await handleInboxRequest(get("/api/inbox"), { limit: null }, {
    apiBaseUrl: API_BASE,
    fetchImpl: stub.fetchImpl,
  });
  assert.equal(response.status, 500);
  assertNoStore(response);
});

test("parseLimit accepts clean integers within bounds and nothing else", () => {
  assert.equal(parseLimit(null, 50, 100), 50);
  assert.equal(parseLimit("", 50, 100), 50);
  assert.equal(parseLimit("1", 50, 100), 1);
  assert.equal(parseLimit("100", 50, 100), 100);
  for (const bad of ["0", "101", "1.5", "1e3", "+1", " 1", "abc", "-1", "0x10"]) {
    assert.equal(parseLimit(bad, 50, 100), null, JSON.stringify(bad));
  }
});

test("the upstream paths are exactly the API's", () => {
  assert.equal(inboxPath(50), "api/v1/conversations?limit=50");
  assert.equal(conversationPath(CONVERSATION), `api/v1/conversations/${CONVERSATION}`);
  assert.equal(messagesPath(CONVERSATION, 100, null), `api/v1/conversations/${CONVERSATION}/messages?limit=100`);
  assert.equal(
    messagesPath(CONVERSATION, 100, CURSOR),
    `api/v1/conversations/${CONVERSATION}/messages?limit=100&before=${CURSOR}`,
  );
});

test("the conversation id pattern accepts UUIDs and refuses other shapes", () => {
  assert.equal(CONVERSATION_ID_PATTERN.test(CONVERSATION), true);
  assert.equal(CONVERSATION_ID_PATTERN.test("c81407b1-4680-469d-9de4-2c34f042081C"), true, "case-insensitive");
  for (const bad of ["", "abc", "..", "a/b", CONVERSATION + "x", CONVERSATION.slice(0, -1)]) {
    assert.equal(CONVERSATION_ID_PATTERN.test(bad), false, JSON.stringify(bad));
  }
});
