import assert from "node:assert/strict";
import test from "node:test";

import { articleViewPath, handleArticleViewRequest } from "../src/views.ts";
import { API_BASE, json, request, stubFetch } from "./helpers.ts";

/**
 * The view beacon's proxy contract (ADR 0035).
 *
 * The beacon is the only thing that makes a counter move, so the properties that
 * matter are the ones that decide whether it is a write: the method, the Origin
 * check, and the two inputs being validated next to the page instead of at the
 * far end of a round trip.
 */

const SLUG = "portable-web-foundation";

function viewUpstream(body: unknown = { data: { counted: true, viewCount: 1 } }, status = 200) {
  return stubFetch({ "api/v1/articles/": () => json(body, status) });
}

test("a same-origin beacon is forwarded to the documented upstream path", async () => {
  const stub = viewUpstream();
  const response = await handleArticleViewRequest(
    request(`/api/articles/${SLUG}/views?locale=zh-CN`),
    { slug: SLUG, locale: "zh-CN" },
    { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
  );
  assert.equal(response.status, 200);
  assert.equal(stub.calls[0]?.init?.method, "POST");
  assert.equal(
    stub.calls[0]?.url,
    `${API_BASE}/${articleViewPath(SLUG, "zh-CN")}`,
    "the upstream path is generated by one function, not spelled twice",
  );
  // The body is the API's answer: a page that wanted the count could show it.
  assert.deepEqual(await response.json(), { data: { counted: true, viewCount: 1 } });
});

test("a beacon from another origin is refused before anything is forwarded", async () => {
  const stub = viewUpstream();
  const response = await handleArticleViewRequest(
    request(`/api/articles/${SLUG}/views`, { headers: { origin: "https://evil.example" } }),
    { slug: SLUG, locale: "zh-CN" },
    { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
  );
  assert.equal(response.status, 403);
  assert.deepEqual(stub.calls, []);
});

test("reading a view with GET is refused: a cached fetch must not move a counter", async () => {
  const stub = viewUpstream();
  for (const method of ["GET", "PUT", "DELETE"]) {
    const response = await handleArticleViewRequest(
      request(`/api/articles/${SLUG}/views`, { method }),
      { slug: SLUG, locale: "zh-CN" },
      { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
    );
    assert.equal(response.status, 405, `${method} is not a view`);
  }
  assert.deepEqual(stub.calls, []);
});

test("a malformed slug or locale is a local 400, and an unconfigured API a 503", async () => {
  const stub = viewUpstream();
  for (const slug of ["Not_A_Slug", "trailing-", "../etc/passwd", ""]) {
    const response = await handleArticleViewRequest(
      request(`/api/articles/${encodeURIComponent(slug || "x")}/views`),
      { slug, locale: "zh-CN" },
      { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
    );
    assert.equal(response.status, 400, `slug ${JSON.stringify(slug)} is rejected locally`);
  }
  const badLocale = await handleArticleViewRequest(
    request(`/api/articles/${SLUG}/views?locale=fr`),
    { slug: SLUG, locale: "fr" },
    { apiBaseUrl: API_BASE, fetchImpl: stub.fetchImpl },
  );
  assert.equal(badLocale.status, 400);
  assert.deepEqual(stub.calls, []);

  const unconfigured = await handleArticleViewRequest(
    request(`/api/articles/${SLUG}/views`),
    { slug: SLUG, locale: "zh-CN" },
    { apiBaseUrl: undefined, fetchImpl: stub.fetchImpl },
  );
  assert.equal(unconfigured.status, 503);
  assert.deepEqual(stub.calls, []);
});
